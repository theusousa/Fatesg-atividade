    private void btnListarAncestorAdded(javax.swing.event.AncestorEvent evt) {//GEN-FIRST:event_btnListarAncestorAdded
        File arquivo = new File("produtos.txt");

if (!arquivo.exists()) {
    JOptionPane.showMessageDialog(this, "O arquivo produtos.txt ainda não existe!");
    return;
}

DefaultTableModel modelo = (DefaultTableModel) tblProdutos.getModel();
modelo.setRowCount(0); 
double total = 0;

try {
    BufferedReader br = new BufferedReader(new FileReader(arquivo));
    String linha;
    while ((linha = br.readLine()) != null) {
        String[] partes = linha.split(";");

        
        if (partes.length != 3) {
            continue;
        }

        try {
            double preco = Double.parseDouble(partes[1].trim().replace(",", "."));
            int quantidade = Integer.parseInt(partes[2].trim());

            modelo.addRow(new Object[]{partes[0].trim(), preco, quantidade});
            total += preco * quantidade;
        } catch (NumberFormatException e) {
           
        }
    }
    br.close();

    lblTotal.setText(String.format("Total do estoque: R$ %.2f", total));
    } catch (IOException e) {
    JOptionPane.showMessageDialog(this, "Erro ao ler o arquivo!");
}
    }//GEN-LAST:event_btnListarAncestorAdded

