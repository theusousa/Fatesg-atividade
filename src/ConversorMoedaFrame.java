    private void btnConverterActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConverterActionPerformed
        if (txtValor.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Digite o valor em reais!");
            return;
        }

        try {
            double reais = Double.parseDouble(txtValor.getText().replace(",", "."));
            String moeda = (String) cmbMoeda.getSelectedItem();
            double convertido;
            String simbolo;

            if (moeda.equals("Dólar")) {
                double COTACAO_DOLAR = 5.40;
                convertido = reais / COTACAO_DOLAR;
                simbolo = "US$";
            } else if (moeda.equals("Euro")) {
                double COTACAO_EURO = 6.00;
                convertido = reais / COTACAO_EURO;
                simbolo = "€";
            } else {
                double COTACAO_LIBRA = 7.10;
                convertido = reais / COTACAO_LIBRA;
                simbolo = "£";
            }

            lblResultado.setText(String.format("%s %.2f", simbolo, convertido));
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Digite um valor válido!");
        }
    }//GEN-LAST:event_btnConverterActionPerformed

