    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        String nome = txtNome.getText().trim();
String preco = txtPreco.getText().trim();
String quantidade = txtQuantidade.getText().trim();

if (nome.isEmpty() || preco.isEmpty() || quantidade.isEmpty()) {
    JOptionPane.showMessageDialog(this, "Preencha todos os campos!");
    return;
}

try {
    FileWriter fw = new FileWriter("produtos.txt", true); // true = não apaga os anteriores
    fw.write(nome + ";" + preco + ";" + quantidade + "\n");
    fw.close();

    JOptionPane.showMessageDialog(this, "Produto salvo!");

    txtNome.setText("");
    txtPreco.setText("");
    txtQuantidade.setText("");
    txtNome.requestFocus();
} catch (IOException e) {
    JOptionPane.showMessageDialog(this, "Erro ao salvar o arquivo!");
}
    }//GEN-LAST:event_btnSalvarActionPerformed

